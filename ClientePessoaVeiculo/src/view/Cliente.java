    private void btnConsultaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnConsultaActionPerformed
        try {
            String host = "localhost";
            int porta = 12345;
            
            Socket clienteSoket = new Socket(host, porta);
            System.out.println("Conexão efetuada com sucesso!");
            
            ObjectOutputStream out = new ObjectOutputStream(clienteSoket.getOutputStream());
            ObjectInputStream in = new ObjectInputStream(clienteSoket.getInputStream());
            
            int id = Integer.parseInt(txtIdPessoa.getText());
            out.writeInt(id);
            out.flush();
            
            Pessoa p = (Pessoa) in.readObject();
            System.out.println("Resposta: " + p.getNome());
            
            lblNome.setText(p.getNome());
            lblSexo.setText(p.getSexo());
            lblIdioma.setText(p.getIdioma());
            
            //Fechamento adequado dos fluxos e do socket
            out.close();
            in.close();
            clienteSoket.close();
        } catch (IOException ex) {
            System.out.println("Erro na comunicação com o servidor");
        } catch (ClassNotFoundException ex) {
            System.out.println("Classe Pessoa não encontrada");
        }
    }//GEN-LAST:event_btnConsultaActionPerformed

