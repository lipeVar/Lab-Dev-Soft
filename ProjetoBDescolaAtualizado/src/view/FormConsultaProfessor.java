    private void btn_consultarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_consultarActionPerformed
        int idProfessor = Integer.parseInt(txt_id.getText());
        ProfessorDAO pDAO = new ProfessorDAO();

        Professor p = pDAO.getProfessor(idProfessor);
        if(p == null){
            limparFormulario();
            JOptionPane.showMessageDialog(this, "Professor nao encontrado");
        }
        else{
            txt_id2.setText(p.getId()+"");
            txt_nome.setText(p.getNome());
            txt_idade.setText(String.valueOf(p.getIdade()));
            cmb_disciplinas.setSelectedItem(p.getDisciplina());
        }
    }//GEN-LAST:event_btn_consultarActionPerformed

